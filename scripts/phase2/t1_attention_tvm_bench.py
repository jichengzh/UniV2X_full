def _round(value: Any, digits: int = 4) -> float | None:
    try:
        return round(float(value), digits)
    except (TypeError, ValueError):
        return None


def _latency_entry(status: str, p50_us: float | None = None, **extra) -> dict[str, Any]:
    entry = {"status": status}
    if p50_us is not None:
        entry["p50_ms"] = _round(p50_us / 1000.0, 6)
        entry["p50_us"] = _round(p50_us, 3)
    entry.update(extra)
    return entry


def _time_vm(vm, args, dev, number: int, repeat: int) -> dict[str, float]:
    vm["main"](*args)
    dev.sync()
    timer = vm.time_evaluator("main", dev, number=number, repeat=repeat)
    result = timer(*args)
    values_us = [x * 1e6 for x in result.results]
    return {
        "mean_us": float(np.mean(values_us)),
        "p50_us": float(np.percentile(values_us, 50)),
        "min_us": float(np.min(values_us)),
        "p95_us": float(np.percentile(values_us, 95)),
    }


def make_mswin_bwa_shape_plan(
    batch: int,
    agents: int,
    h: int,
    w: int,
    channels: int,
    heads: int,
    dim_head: int,
    window_size: int,
    prune_rate_pct: int,
) -> dict[str, Any]:
    if h % window_size != 0 or w % window_size != 0:
        raise ValueError("h and w must be divisible by window_size")
    inner_dim = heads * dim_head
    new_h = h // window_size
    new_w = w // window_size
    window_tokens = window_size * window_size
    flat_m = batch * agents * h * w
    return {
        "input_shape": [batch, agents, h, w, channels],
        "batch": batch,
        "agents": agents,
        "h": h,
        "w": w,
        "channels": channels,
        "heads": heads,
        "dim_head": dim_head,
        "inner_dim": inner_dim,
        "window_size": window_size,
        "new_h": new_h,
        "new_w": new_w,
        "window_tokens": window_tokens,
        "window_batches": batch * agents * heads * new_h * new_w,
        "qkv_shape_mkn": [flat_m, channels, inner_dim],
        "out_shape_mkn": [flat_m, inner_dim, channels],
        "prune_rate_pct": prune_rate_pct,
    }


