def build_relax_matmul(dtype: str, m: int, k: int, n: int, out_dtype: str | None):
    import tvm
    from tvm import relax

    bb = relax.BlockBuilder()
    x = relax.Var("x", relax.TensorStructInfo((m, k), dtype))
    w = relax.Var("w", relax.TensorStructInfo((k, n), dtype))
    with bb.function("main", [x, w]):
        with bb.dataflow():
            y = bb.emit(relax.op.matmul(x, w, out_dtype=out_dtype) if out_dtype else relax.op.matmul(x, w))
            gv = bb.emit_output(y)
        bb.emit_func_output(gv)
    return bb.finalize()


def compile_relax_module(mod, target):
    import tvm
    from tvm import relax
    import tvm.s_tir.dlight as dl

    seq = tvm.transform.Sequential([
        relax.transform.LegalizeOps(),
        relax.transform.AnnotateTIROpPattern(),
        relax.transform.FuseOps(),
        relax.transform.FuseTIR(),
    ])
    with target, tvm.transform.PassContext(opt_level=3):
        mod = seq(mod)
        mod = dl.ApplyDefaultSchedule(
            dl.gpu.Matmul(),
            dl.gpu.GEMV(),
            dl.gpu.Reduction(),
            dl.gpu.GeneralReduction(),
            dl.gpu.Fallback(),
        )(mod)
        return tvm.compile(mod, target=target)


def _reshape_windows(expr, plan: dict[str, Any]):
    from tvm import relax

    b, l, h, w, heads, dim_head = (
        plan["batch"],
        plan["agents"],
        plan["h"],
        plan["w"],
        plan["heads"],
        plan["dim_head"],
    )
    ws = plan["window_size"]
    new_h = plan["new_h"]
    new_w = plan["new_w"]
    expr = relax.op.reshape(expr, (b, l, new_h, ws, new_w, ws, heads, dim_head))
    expr = relax.op.permute_dims(expr, axes=[0, 1, 6, 2, 4, 3, 5, 7])
    return relax.op.reshape(expr, (plan["window_batches"], plan["window_tokens"], dim_head))


def _unshape_windows(expr, plan: dict[str, Any]):
    from tvm import relax

    b, l, heads, dim_head = plan["batch"], plan["agents"], plan["heads"], plan["dim_head"]
    ws, new_h, new_w = plan["window_size"], plan["new_h"], plan["new_w"]
    expr = relax.op.reshape(expr, (b, l, heads, new_h, new_w, ws, ws, dim_head))
    expr = relax.op.permute_dims(expr, axes=[0, 1, 3, 5, 4, 6, 2, 7])
    return relax.op.reshape(expr, (b * l * plan["h"] * plan["w"], plan["inner_dim"]))


def build_relax_mswin_bwa_fp16(plan: dict[str, Any]):
    from tvm import relax

    b, l, h, w, c = plan["input_shape"]
    inner = plan["inner_dim"]
    tokens = plan["window_tokens"]
    bb = relax.BlockBuilder()
    x = relax.Var("x", relax.TensorStructInfo((b, l, h, w, c), "float16"))
    wq = relax.Var("wq", relax.TensorStructInfo((c, inner), "float16"))
    wk = relax.Var("wk", relax.TensorStructInfo((c, inner), "float16"))
    wv = relax.Var("wv", relax.TensorStructInfo((c, inner), "float16"))
    wo = relax.Var("wo", relax.TensorStructInfo((inner, c), "float16"))
    pos = relax.Var("pos", relax.TensorStructInfo((tokens, tokens), "float16"))
    with bb.function("main", [x, wq, wk, wv, wo, pos]):
        with bb.dataflow():
            x2 = bb.emit(relax.op.reshape(x, (b * l * h * w, c)))
            q = bb.emit(relax.op.matmul(x2, wq))
            k = bb.emit(relax.op.matmul(x2, wk))
            v = bb.emit(relax.op.matmul(x2, wv))
            q_w = bb.emit(_reshape_windows(q, plan))
            k_w = bb.emit(_reshape_windows(k, plan))
            v_w = bb.emit(_reshape_windows(v, plan))
            k_t = bb.emit(relax.op.permute_dims(k_w, axes=[0, 2, 1]))
            dots = bb.emit(relax.op.matmul(q_w, k_t))
            pos_b = bb.emit(relax.op.reshape(pos, (1, tokens, tokens)))
            dots = bb.emit(relax.op.add(dots, pos_b))
            attn = bb.emit(relax.op.nn.softmax(dots, axis=-1))
            out = bb.emit(relax.op.matmul(attn, v_w))
            out2 = bb.emit(_unshape_windows(out, plan))
            y = bb.emit(relax.op.matmul(out2, wo))
            y = bb.emit(relax.op.reshape(y, (b, l, h, w, c)))
            gv = bb.emit_output(y)
        bb.emit_func_output(gv)
    return bb.finalize()


