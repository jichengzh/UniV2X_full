def _hmsa_emit_relation_body(bb, q0, k0, v0, q1, k1, v1, rels, outs, plan: dict[str, Any], mixed: bool):
    from tvm import relax

    heads = plan["heads"]
    spatial = plan["spatial_tokens"]
    dim_head = plan["dim_head"]
    r00a, r01a, r10a, r11a, r00m, r01m, r10m, r11m = rels
    wo0, wo1 = outs
    pair_score = _hmsa_pair_score_mixed if mixed else _hmsa_pair_score
    message = _hmsa_message_mixed if mixed else _hmsa_message
    project = _hmsa_project_out_mixed if mixed else _hmsa_project_out

    s00 = pair_score(bb, q0, r00a, k0, dim_head)
    s01 = pair_score(bb, q0, r01a, k1, dim_head)
    s10 = pair_score(bb, q1, r10a, k0, dim_head)
    s11 = pair_score(bb, q1, r11a, k1, dim_head)
    w00, w01 = _softmax_two(bb, s00, s01)
    w10, w11 = _softmax_two(bb, s10, s11)
    msg00 = message(bb, v0, r00m)
    msg01 = message(bb, v1, r01m)
    msg10 = message(bb, v0, r10m)
    msg11 = message(bb, v1, r11m)
    out0 = _weighted_pair_sum(bb, w00, msg00, w01, msg01, heads, spatial)
    out1 = _weighted_pair_sum(bb, w10, msg10, w11, msg11, heads, spatial)
    y0 = project(bb, out0, wo0, plan)
    y1 = project(bb, out1, wo1, plan)
    y = bb.emit(relax.op.concat([y0, y1], axis=0))
    b, l, h, w, c = plan["input_shape"]
    return bb.emit(relax.op.reshape(y, (b, l, h, w, c)))


def build_relax_hmsa_relation_core_fp16(plan: dict[str, Any]):
    from tvm import relax

    b, l, h, w, c = plan["input_shape"]
    if b != 1 or l != 2:
        raise ValueError("HMSA minimal relation core currently requires B=1,L=2")
    heads, dim_head, inner = plan["heads"], plan["dim_head"], plan["inner_dim"]
    spatial = plan["spatial_tokens"]
    bb = relax.BlockBuilder()
    q0 = relax.Var("q0", relax.TensorStructInfo((heads, spatial, dim_head), "float16"))
    k0 = relax.Var("k0", relax.TensorStructInfo((heads, spatial, dim_head), "float16"))
    v0 = relax.Var("v0", relax.TensorStructInfo((heads, spatial, dim_head), "float16"))
    q1 = relax.Var("q1", relax.TensorStructInfo((heads, spatial, dim_head), "float16"))
    k1 = relax.Var("k1", relax.TensorStructInfo((heads, spatial, dim_head), "float16"))
    v1 = relax.Var("v1", relax.TensorStructInfo((heads, spatial, dim_head), "float16"))
    r00a = relax.Var("r00a", relax.TensorStructInfo((heads, dim_head, dim_head), "float16"))
    r01a = relax.Var("r01a", relax.TensorStructInfo((heads, dim_head, dim_head), "float16"))
    r10a = relax.Var("r10a", relax.TensorStructInfo((heads, dim_head, dim_head), "float16"))
    r11a = relax.Var("r11a", relax.TensorStructInfo((heads, dim_head, dim_head), "float16"))
    r00m = relax.Var("r00m", relax.TensorStructInfo((heads, dim_head, dim_head), "float16"))
    r01m = relax.Var("r01m", relax.TensorStructInfo((heads, dim_head, dim_head), "float16"))
    r10m = relax.Var("r10m", relax.TensorStructInfo((heads, dim_head, dim_head), "float16"))
