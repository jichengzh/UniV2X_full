def _hmsa_pair_score(bb, q, rel_att, k, dim_head: int):
    from tvm import relax

    q_rel = bb.emit(relax.op.matmul(q, rel_att))
    prod = bb.emit(relax.op.multiply(q_rel, k))
    score = bb.emit(relax.op.sum(prod, axis=2))
    scale = relax.const(dim_head ** -0.5, "float16")
    return bb.emit(relax.op.multiply(score, scale))


def _hmsa_pair_score_mixed(bb, q, rel_att, k, dim_head: int):
    from tvm import relax

    q_rel = bb.emit(relax.op.matmul(q, rel_att, out_dtype="int32"))
    q_rel = bb.emit(relax.op.astype(q_rel, "float16"))
    k_fp = bb.emit(relax.op.astype(k, "float16"))
    prod = bb.emit(relax.op.multiply(q_rel, k_fp))
    score = bb.emit(relax.op.sum(prod, axis=2))
    scale = relax.const(dim_head ** -0.5, "float16")
    return bb.emit(relax.op.multiply(score, scale))


def _softmax_two(bb, score0, score1):
    from tvm import relax

    exp0 = bb.emit(relax.op.exp(score0))
    exp1 = bb.emit(relax.op.exp(score1))
    denom = bb.emit(relax.op.add(exp0, exp1))
    return bb.emit(relax.op.divide(exp0, denom)), bb.emit(relax.op.divide(exp1, denom))


def _hmsa_message(bb, v, rel_msg):
    from tvm import relax

    return bb.emit(relax.op.matmul(v, rel_msg))


def _hmsa_message_mixed(bb, v, rel_msg):
    from tvm import relax

    msg = bb.emit(relax.op.matmul(v, rel_msg, out_dtype="int32"))
    return bb.emit(relax.op.astype(msg, "float16"))


def _weighted_pair_sum(bb, w0, msg0, w1, msg1, heads: int, spatial_tokens: int):
    from tvm import relax

    w0 = bb.emit(relax.op.reshape(w0, (heads, spatial_tokens, 1)))
    w1 = bb.emit(relax.op.reshape(w1, (heads, spatial_tokens, 1)))
    part0 = bb.emit(relax.op.multiply(w0, msg0))
    part1 = bb.emit(relax.op.multiply(w1, msg1))
    return bb.emit(relax.op.add(part0, part1))


def _hmsa_project_out(bb, out, wo, plan: dict[str, Any]):
    from tvm import relax

    out = bb.emit(relax.op.permute_dims(out, axes=[1, 0, 2]))
    out = bb.emit(relax.op.reshape(out, (plan["spatial_tokens"], plan["inner_dim"])))
    return bb.emit(relax.op.matmul(out, wo))


def _hmsa_project_out_mixed(bb, out, wo, plan: dict[str, Any]):
    from tvm import relax

    out = bb.emit(relax.op.permute_dims(out, axes=[1, 0, 2]))
    out = bb.emit(relax.op.reshape(out, (plan["spatial_tokens"], plan["inner_dim"])))
    out = bb.emit(relax.op.astype(out, "int8"))
    y = bb.emit(relax.op.matmul(out, wo, out_dtype="int32"))
    return bb.emit(relax.op.astype(y, "float16"))


def _hmsa_project_qkv(bb, x, wq, wk, wv, plan: dict[str, Any]):
    from tvm import relax

    heads, dim_head = plan["heads"], plan["dim_head"]
    spatial = plan["spatial_tokens"]
    q = bb.emit(relax.op.matmul(x, wq))
    k = bb.emit(relax.op.matmul(x, wk))
    v = bb.emit(relax.op.matmul(x, wv))
    q = bb.emit(relax.op.reshape(q, (spatial, heads, dim_head)))
    k = bb.emit(relax.op.reshape(k, (spatial, heads, dim_head)))
    v = bb.emit(relax.op.reshape(v, (spatial, heads, dim_head)))
    q = bb.emit(relax.op.permute_dims(q, axes=[1, 0, 2]))
    k = bb.emit(relax.op.permute_dims(k, axes=[1, 0, 2]))
    v = bb.emit(relax.op.permute_dims(v, axes=[1, 0, 2]))
    return q, k, v


